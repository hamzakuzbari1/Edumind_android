def _curriculum_context(body: dict[str, object]) -> tuple[str, str, WritingGoal, str, str]:

    curriculum = body.get(WRITING_CURRICULUM_KEY) or {}

    if not isinstance(curriculum, dict):

        curriculum = {}

    blueprint = body.get(WRITING_BLUEPRINT_KEY) or {}

    if not isinstance(blueprint, dict):

        blueprint = {}

    official_cefr = str(curriculum.get("official_cefr") or blueprint.get("official_cefr") or "B1")

    arc_stage = str(curriculum.get("arc_stage") or blueprint.get("curriculum_arc") or "")

    chain_id = str(curriculum.get("chain_id") or blueprint.get("chain_id") or "")

    node_id = str(curriculum.get("chain_node_id") or blueprint.get("chain_node_id") or "")

    raw_goal = (

        body.get(WRITING_GOAL_KEY)

        or curriculum.get("personal_goal")

        or blueprint.get("personal_goal")

        or "general_english"

    )

    try:

        goal = WritingGoal(str(raw_goal))

    except ValueError:

        goal = WritingGoal.general_english

    return official_cefr, arc_stage, goal, chain_id, node_id





async def submit_writing_draft_for_evaluation(

    db: AsyncSession,

    *,

    student_id: int,

    content_item_id: int,

    draft_text: str,

    complete_if_ready: bool = False,

    language_id: int,

) -> dict:

    item = await get_content_item(

        db,

        student_id=student_id,

        content_id=content_item_id,

        content_type="writing_prompt",

        skill=LanguageSkill.writing,

        level_skill=LanguageSkill.writing,

    )

    if not item:

        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Writing lesson not found")



    body = dict(item.body_json or {})
    owner = body.get("owner_student_id")
    if owner is not None and str(owner) != str(student_id):
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Writing lesson not found")

    if WRITING_BLUEPRINT_KEY not in body:

        raise HTTPException(

            status_code=status.HTTP_422_UNPROCESSABLE_ENTITY,

            detail={"code": "missing_blueprint", "message": "Lesson was not generated by writing runtime (no blueprint)"},

        )



    if not draft_text.strip():

        raise HTTPException(status_code=status.HTTP_422_UNPROCESSABLE_ENTITY, detail="Draft text is required")



    result, updated_body = await process_writing_draft_turn(

        student_id=student_id,

        content_item_id=content_item_id,

        draft_text=draft_text,

        body_json=body,

        force_complete=complete_if_ready,

    )



    item.body_json = updated_body

    await db.flush()



    evaluation = result.evaluation

    plan_dict = result.revision_plan.to_revision_plan_out_dict()

    feedback_dict = revision_plan_to_feedback(result.revision_plan).to_student_dict()

    evaluation_display = build_student_evaluation_display(evaluation)

    educational_analysis = build_student_educational_analysis(evaluation.claude_analysis)

    official_cefr, arc_stage, goal, chain_id, node_id = _curriculum_context(body)



    lesson_progress = None

    if result.completed:

        prog_row = await ensure_progression_row(db, student_id=student_id, language_id=language_id)

        prog_state = writing_state_from_payload(

            dict(prog_row.promotion_readiness_json or {}) if prog_row else {}

        )



        await run_writing_progression_after_complete(

            db,

            student_id=student_id,

            language_id=language_id,

            content_item_id=content_item_id,

            goal=goal,

            official_cefr=OfficialWritingCEFR(official_cefr),

            chain_id=chain_id,

            node_id=node_id,

            evaluation=evaluation,

            revision_count=result.revision_number,

        )



        prog_row = await ensure_progression_row(db, student_id=student_id, language_id=language_id)

        prog_state = writing_state_from_payload(

            dict(prog_row.promotion_readiness_json or {}) if prog_row else {}

        )

        history_phrases = tuple(prog_state.get("history_phrases") or [])



        summary = build_lesson_progress_summary(

            evaluation=evaluation,

            official_cefr=official_cefr,

            arc_stage=arc_stage,

            goal=goal,

            what_improved=result.revision_plan.what_improved,

        )

        feedback = build_lesson_completion_feedback(

            evaluation=evaluation,

            official_cefr=official_cefr,

            goal=goal,

            chain_id=chain_id,

            node_id=node_id,

            progression_state=prog_state,

            history_phrases=history_phrases,

        )

        merged = {**summary.to_student_dict(), **feedback.to_student_dict()}

        merged["improved_today"] = list(

            dict.fromkeys(list(summary.improved_today) + list(feedback.what_you_did_well))

        )

        lesson_progress = merged



    payload = {

        "content_item_id": content_item_id,

        "draft_id": evaluation.draft_id,

        "word_count": evaluation.word_count,

        "revision_number": result.revision_number,

        "completed": result.completed,

        "ready_to_complete": evaluation.revision_readiness.ready,

        "lifecycle": result.session.lifecycle.value,

        "feedback": feedback_dict,

        "revision_plan": plan_dict,

        "evaluation_display": evaluation_display.to_student_dict(),

        "educational_analysis": educational_analysis,

        "lesson_progress": lesson_progress,

        "completion": evaluation.completion.to_persistence_dict(),

        "comparison": evaluation.comparison.to_persistence_dict() if evaluation.comparison else None,

        "runtime_version": result.runtime_version,

    }

    return WritingDraftSubmitOut.model_validate(payload).model_dump()
